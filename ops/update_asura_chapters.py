"""Refresh public chapter metadata and links; never download chapter content."""
import argparse
import concurrent.futures
import datetime
import html
import json
import os
import tempfile
from html.parser import HTMLParser
from pathlib import Path
import urllib.request
from urllib.parse import urljoin, urlsplit

ROOT = Path(__file__).resolve().parents[1]


def decode_prop(value):
    if not isinstance(value, list) or len(value) != 2:
        raise ValueError('Unexpected chapter metadata encoding')
    kind, data = value
    if kind == 1:
        return [decode_prop(item) for item in data]
    if kind == 0:
        return {key: decode_prop(item) for key, item in data.items()} if isinstance(data, dict) else data
    raise ValueError(f'Unsupported metadata type {kind}')


class ChapterParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.chapters = None
        self.links = {}
        self.total = None
        self.canonical = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'link' and attrs.get('rel') == 'canonical':
            self.canonical = attrs.get('href')
        if tag == 'a' and attrs.get('href'):
            path = urlsplit(attrs['href']).path.rstrip('/')
            self.links[path] = attrs['href']
        if tag == 'astro-island' and 'ChapterList' in attrs.get('component-url', ''):
            props = json.loads(attrs['props'])
            self.chapters = decode_prop(props['chapters'])
            self.total = decode_prop(props['totalChapters'])


def parse_chapters(document, series_url):
    parser = ChapterParser()
    parser.feed(document)
    if parser.chapters is None:
        raise ValueError('Public chapter list was not found')
    base = urlsplit(series_url)
    prefix = base.path.rstrip('/') + '/chapter/'
    result = []
    for item in parser.chapters:
        number = item.get('number')
        if isinstance(number, bool) or not isinstance(number, (int, float)) or number < 0:
            raise ValueError('Invalid chapter number')
        # Every target must appear as an actual published link in the page.
        path = prefix + str(number)
        href = parser.links.get(path)
        if href is None and isinstance(number, float) and number.is_integer():
            href = parser.links.get(prefix + str(int(number)))
        if href is None:
            raise ValueError(f'Published link missing for chapter {number}')
        target = urljoin(series_url, html.unescape(href))
        parsed = urlsplit(target)
        if parsed.scheme != 'https' or parsed.netloc != base.netloc or not parsed.path.startswith(prefix):
            raise ValueError('Chapter link points outside the original series')
        result.append({'number': number, 'title': item.get('title') or '', 'url': target,
                       'premium': bool(item.get('is_premium')), 'publishedAt': item.get('published_at')})
    if len({item['number'] for item in result}) != len(result):
        raise ValueError('Duplicate chapter numbers')
    if len(result) != parser.total:
        raise ValueError(f'Incomplete chapter list: {len(result)} of {parser.total}')
    return sorted(result, key=lambda item: item['number'])


def fetch_title(entry):
    series_url = entry['sourceUrl'].split('/chapter/')[0]
    request = urllib.request.Request(series_url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(request, timeout=30) as response:
        document = response.read().decode('utf-8')
    chapters = parse_chapters(document, series_url)
    return entry['id'], {'seriesUrl': series_url, 'chapters': chapters}


def write_snapshots(entries, snapshot, root=ROOT):
    """Prepare every output before changing files; publish the small index last."""
    outputs = {}
    summaries = {}
    loaders = ["// Generated by scripts/update_asura_chapters.py; do not edit by hand.",
               "// Functions defer chapter evaluation until one title is requested.",
               "export const chapterLoaders: Record<string, () => Promise<unknown>> = {"]
    for entry in entries:
        title_id = entry['id']
        if not title_id or any(char not in 'abcdefghijklmnopqrstuvwxyz0123456789-' for char in title_id):
            raise ValueError('Invalid title identifier')
        listing = snapshot['titles'][title_id]
        chapters = listing['chapters']
        series_url = entry['sourceUrl'].split('/chapter/')[0]
        if listing['seriesUrl'] != series_url:
            raise ValueError(f'Series URL mismatch for {title_id}')
        checked_at = listing.get('checkedAt', snapshot.get('checkedAt'))
        if not checked_at:
            raise ValueError(f'Missing check timestamp for {title_id}')
        document = {'schemaVersion': 1, 'provider': 'asura', 'titleId': title_id,
                    'seriesUrl': series_url, 'checkedAt': checked_at,
                    'chapterCount': len(chapters), 'chapters': chapters}
        relative = f'content/chapters/asura/{title_id}.json'
        outputs[relative] = json.dumps(document, ensure_ascii=False, indent=2) + '\n'
        summaries[title_id] = {'seriesUrl': series_url, 'chapterCount': len(chapters), 'checkedAt': checked_at}
        if chapters:
            summaries[title_id]['firstChapter'] = chapters[0]['number']
        if entry.get('bundleChapters', True):
            loaders.append(f"  'asura:{title_id}': async () => require('../../{relative}'),")
    loaders.append('};')
    outputs['src/data/chapter-loaders.ts'] = '\n'.join(loaders) + '\n'
    outputs['src/data/asura-chapter-index.json'] = json.dumps({'schemaVersion': 1, 'titles': summaries}, ensure_ascii=False, indent=2) + '\n'
    staged = []
    try:
        for relative, text in outputs.items():
            target = root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=target.parent, delete=False) as temporary:
                temporary.write(text)
                staged.append((Path(temporary.name), target))
        for temporary, target in staged:
            os.replace(temporary, target)
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)
    print(f"Saved {sum(len(item['chapters']) for item in snapshot['titles'].values())} chapter links in per-title snapshots")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--from-snapshot', type=Path, help='Migrate an existing aggregate snapshot without network requests')
    args = parser.parse_args()
    entries = json.loads((ROOT / 'src/data/asura-titles.json').read_text())
    if args.from_snapshot:
        snapshot = json.loads(args.from_snapshot.read_text())
    else:
        result = {}
        with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
            for title_id, data in pool.map(fetch_title, entries):
                result[title_id] = data
                print(f"{title_id}: {len(data['chapters'])} chapters", flush=True)
        snapshot = {'checkedAt': datetime.datetime.now(datetime.timezone.utc).isoformat(), 'titles': result}
    write_snapshots(entries, snapshot)


if __name__ == '__main__':
    main()
